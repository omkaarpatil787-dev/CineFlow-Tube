package com.cineflow.tube.data.model

import kotlinx.serialization.Serializable

@Serializable
data class StreamItem(
    val id: String,
    val title: String,
    val uploaderName: String,
    val uploaderUrl: String? = null,
    val uploaderAvatarUrl: String? = null,
    val thumbnailUrl: String,
    val durationSeconds: Long = 0,
    val durationString: String = "",
    val views: Long = 0,
    val viewsFormatted: String = "",
    val uploadedDateFormatted: String = "",
    val isLive: Boolean = false
)

@Serializable
data class VideoStreamFormat(
    val url: String,
    val quality: String, // "1080p", "720p", "480p", "360p"
    val format: String,  // "WEBM", "MPEG_4"
    val width: Int = 0,
    val height: Int = 0,
    val fps: Int = 30,
    val bitrate: Long = 0,
    val isVideoOnly: Boolean = false
)

@Serializable
data class AudioStreamFormat(
    val url: String,
    val format: String,  // "OPUS", "M4A"
    val quality: String, // "160k", "128k", "64k"
    val bitrate: Long = 0,
    val mimeType: String = "audio/webm"
)

@Serializable
data class SubtitleTrack(
    val url: String,
    val mimeType: String = "text/vtt",
    val name: String,
    val language: String,
    val isAutoGenerated: Boolean = false
)

@Serializable
data class Chapter(
    val title: String,
    val startSeconds: Long,
    val thumbnail: String? = null
)

@Serializable
data class SponsorSegment(
    val category: String, // "sponsor", "selfpromo", "interaction", "intro", "outro"
    val startSeconds: Float,
    val endSeconds: Float,
    val actionType: String = "skip"
)

@Serializable
data class CommentItem(
    val id: String,
    val author: String,
    val authorAvatarUrl: String? = null,
    val content: String,
    val publishedTime: String = "",
    val likeCount: Long = 0,
    val replyCount: Long = 0,
    val isHearted: Boolean = false,
    val isPinned: Boolean = false
)

@Serializable
data class CustomPlaylist(
    val id: String,
    val title: String,
    val description: String = "",
    val thumbnailUrl: String = "",
    val items: List<StreamItem> = emptyList(),
    val createdAt: Long = System.currentTimeMillis()
)

@Serializable
data class DownloadItem(
    val id: String,
    val title: String,
    val uploaderName: String,
    val thumbnailUrl: String,
    val quality: String,
    val format: String = "MP4",
    val bytesDownloaded: Long = 0,
    val totalBytes: Long = 0,
    val isCompleted: Boolean = false,
    val localFilePath: String? = null,
    val timestamp: Long = System.currentTimeMillis()
)

@Serializable
data class StreamingInstance(
    val url: String,
    val name: String,
    val type: String, // "PIPED" or "INVIDIOUS"
    val pingMs: Long = -1,
    val isHealthy: Boolean = false,
    val isCustom: Boolean = false
)

@Serializable
data class StreamDetails(
    val id: String,
    val title: String,
    val description: String,
    val uploaderName: String,
    val uploaderChannelId: String,
    val uploaderAvatarUrl: String? = null,
    val uploaderSubscriberCount: String = "",
    val views: Long = 0,
    val viewsFormatted: String = "",
    val likes: Long = 0,
    val dislikes: Long = 0,
    val durationSeconds: Long = 0,
    val hlsUrl: String? = null,
    val dashUrl: String? = null,
    val videoStreams: List<VideoStreamFormat> = emptyList(),
    val audioStreams: List<AudioStreamFormat> = emptyList(),
    val subtitles: List<SubtitleTrack> = emptyList(),
    val chapters: List<Chapter> = emptyList(),
    val sponsorSegments: List<SponsorSegment> = emptyList(),
    val comments: List<CommentItem> = emptyList(),
    val relatedVideos: List<StreamItem> = emptyList()
)
